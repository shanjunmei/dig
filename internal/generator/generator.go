const tagBuild = model.TagBuild
const diPkgPath = model.DiPkgPath

// headerTemplate defines the fixed header for generated files.
const headerTemplate = `// Code generated by %s; DO NOT EDIT.

//go` + `:generate go run -mod=mod %s/cmd/%s %s
//go:build !%s
// +build !%s

package %s

`

// Generator holds dependencies for code generation.
type Generator struct {
	logger *logger.Logger
	cfg    *config.Config
}

// NewGenerator creates a new Generator instance.
func NewGenerator(logger *logger.Logger, cfg *config.Config) *Generator {
	return &Generator{logger: logger, cfg: cfg}
}

// WriteGeneratedCode generates code and writes it to the target file.
func (g *Generator) WriteGeneratedCode(pkg *packages.Package, target *model.GenTarget, nodes []model.Node, refCount map[string]int, importAliasMap, pkgAliasMap, pkgNameMap map[string]string, fset *token.FileSet) error {
	outFile := filepath.Base(target.File)
	code, err := g.GenerateCode(nodes, refCount, pkg.Name, target.FuncName, pkg.PkgPath, importAliasMap, pkgAliasMap, pkgNameMap, fset, target.Node.Type.Params, outFile)
	if err != nil {
		return err
	}

	// Post-generation safety net: type-check the freshly formatted generated
	// file before writing it. See typeCheckGenerated for the full contract.
	// It is opt-in via Config.TypeCheckNet: enabled by default, but disabled
	// for large `./...` runs where reloading the package graph per file is
	// expensive. The net only ever fires on an INTERNAL generator bug, never
	// on user code (user errors are caught earlier at load time or by the
	// extractor's checkContractVisibility pre-check).
	if g.cfg.TypeCheckNet {
		if netErr := g.typeCheckGenerated(target.File, []byte(code), pkg); netErr != nil {
			// netErr is an INTERNAL generator bug OR a digen-contract violation
			// that slipped past the pre-check (e.g. on an IR-cache hit). Do NOT
			// write the bad file to disk. Bubble it up to the caller/orchestrator.
			return netErr
		}
	}

	return os.WriteFile(target.File, []byte(code), 0644)
}

// typeCheckGenerated is a best-effort post-generation "safety net".
//
// It type-checks the freshly formatted generated file inside its owning package
// using an Overlay that replaces <pkg>/dig_gen.go with the generated content.
//
// Why this is sound (and can ONLY indicate a generator bug):
//   - The loader (internal/loader) loads the user's source with -tags=digen,
//     which excludes this file via its `//go:build !digen` constraint. A user's
//     own compile error is therefore caught at load time and aborts before any
//     generation runs.
//   - Here we load WITHOUT -tags=digen (so the generated file is INCLUDED via
//     the overlay and the user's digen-tagged source is EXCLUDED). Consequently
//     any compile error whose position lands on the generated file is, by
//     construction, an INTERNAL generator bug — never a user error.
//
// This net is a last-resort fail-safe for UNKNOWN generation bugs only; known
// cases are blocked earlier by semantic rules in the extractor. It must NOT
// mask those nor fire on user errors.
//
// Best-effort: if the type-check infrastructure itself fails to load (overlay/
// environment issue, missing module graph, etc.) we do NOT fail generation — we
// simply skip the net and let the file be written normally. The net is a bonus,
// never a hard blocker that breaks valid generation.
func (g *Generator) typeCheckGenerated(genFile string, content []byte, mainPkg *packages.Package) error {
	// go/packages requires ABSOLUTE paths in the Overlay map. digen often runs
	// with cfg.Paths == ["."] (the default), which makes target.File a relative
	// path like "dig_gen.go". A relative overlay key never matches the absolute
	// path go/packages computes internally, so the overlay silently no-ops and
	// the net either (a) fails with "file not found" on first generation (no
	// dig_gen.go on disk yet) or (b) worse, type-checks the STALE on-disk
	// dig_gen.go instead of the freshly generated content — defeating the net
	// entirely. Normalize to an absolute path so the overlay actually applies.
	absGenFile, err := filepath.Abs(genFile)
	if err != nil {
		g.logger.Debugf("type-check safety net skipped (abs path failed): %v", err)
		return nil
	}
	dir := filepath.Dir(absGenFile)
	cfg := &packages.Config{
		Mode: packages.NeedTypes | packages.NeedTypesInfo,
		// Deliberately NO "-tags=digen": with that tag the generated file is
		// excluded by its //go:build !digen constraint. We load the package as
		// it would be compiled in a real `go build` (user digen-tagged source
		// excluded, generated file included via the overlay).
		Overlay: map[string][]byte{absGenFile: content},
	}

	pkgs, err := packages.Load(cfg, dir)
	if err != nil {
		// Infrastructure/overlay failure: non-fatal, skip the net.
		g.logger.Debugf("type-check safety net skipped (packages.Load failed): %v", err)
		return nil
	}

	var genErrors []packages.Error
	for _, p := range pkgs {
		for _, e := range p.Errors {
			if errorInGeneratedFile(e, absGenFile) {
				genErrors = append(genErrors, e)
			}
		}
	}
	if len(genErrors) == 0 {
		return nil
	}

	// Classify the errors. A "undefined: X" error where X is a main-package
	// symbol DEFINED inside a //go:build digen file is a DIGEN-CONTRACT
	// VIOLATION (user error) — the extractor's checkContractVisibility pre-check
	// normally catches these, but it is skipped on IR-cache hits, so the net is
	// the backstop. Everything else is a genuine INTERNAL generator bug.
	digenNames := collectDigenDefinedMainNames(mainPkg)
	var contractErrs, internalErrs []packages.Error
	for _, e := range genErrors {
		if name, ok := undefinedMainPkgSymbol(e.Msg); ok && digenNames[name] {
			contractErrs = append(contractErrs, e)
		} else {
			internalErrs = append(internalErrs, e)
		}
	}

	// Prefer reporting a contract violation: it is the root cause the user must
	// fix, and any other errors in the same broken file are almost always
	// cascading from the missing symbol.
	if len(contractErrs) > 0 {
		var b strings.Builder
		b.WriteString("digen contract violation: the generated file ")
		b.WriteString(genFile)
		b.WriteString(" failed type-checking because it references symbol(s) defined inside a //go:build digen file of the main package.\n")
		b.WriteString("At a normal `go build` (without the digen tag) that file is excluded, so the generated dig_gen.go cannot see those symbols.\n")
		b.WriteString("Move the definition(s) into a file WITHOUT the //go:build digen constraint (e.g. types.go), or into an imported package.\n")
		for _, e := range contractErrs {
			fmt.Fprintf(&b, "  %s: %s\n", e.Pos, e.Msg)
		}
		return fmt.Errorf("%s", b.String())
	}

	// No contract violation: this is a genuine INTERNAL generator bug. Never
	// phrase it as "your code is wrong" or merely as "undefined: X". Guide the
	// user to file a GitHub issue with a pre-filled, one-click report (plus a
	// copy/paste template for non-interactive environments like CI).
	var details strings.Builder
	for _, e := range internalErrs {
		fmt.Fprintf(&details, "  %s: %s\n", e.Pos, e.Msg)
	}

	issueTitle := "digen generated code failed type-check (internal generator bug)"
	issueBody := buildGeneratorBugReport(absGenFile, details.String())
	reportURL := buildIssueReportURL(issueTitle, issueBody)

	var b strings.Builder
	b.WriteString("digen internal generator error: the generated file ")
	b.WriteString(genFile)
	b.WriteString(" failed type-checking.\n")
	b.WriteString("Most likely cause: the generated code references a type, function, or variable that is DEFINED in your di.go (or another `//go:build digen` file). ")
	b.WriteString("That file is excluded when building WITHOUT the digen tag, so the generated code cannot see the symbol. ")
	b.WriteString("Move such definitions to a file WITHOUT the `//go:build digen` constraint, or to an imported package.\n")
	b.WriteString("If you are certain every referenced symbol lives outside digen-tagged files, this may be a genuine internal generator bug. ")
	b.WriteString("Please help us fix it - file a bug report (a GitHub account is enough):\n")
	fmt.Fprintf(&b, "  Click to open a pre-filled report: %s\n", reportURL)
	b.WriteString("\n  Or paste the template below at: ")
	b.WriteString(digenIssueBaseURL)
	b.WriteString("\n\n")
	b.WriteString("==== bug report template (copy/paste) ====\n")
	b.WriteString(issueBody)
	b.WriteString("\n==== end of template ====\n")
	return fmt.Errorf("%s", b.String())
}

// digenIssueBaseURL is where internal generator bugs should be reported.
const digenIssueBaseURL = "https://github.com/shanjunmei/dig/issues/new"

// buildIssueReportURL returns a GitHub "new issue" URL with the title and body
// pre-filled via query parameters, so a user can click once and have everything
// ready to submit.
func buildIssueReportURL(title, body string) string {
	q := url.Values{}
	q.Set("title", title)
	q.Set("body", body)
	return digenIssueBaseURL + "?" + q.Encode()
}

// buildGeneratorBugReport assembles a self-contained bug-report body for an
// internal generator error, ready to paste into a GitHub issue.
func buildGeneratorBugReport(genFile, errorLocations string) string {
	var b strings.Builder
	b.WriteString("## What happened\n")
	b.WriteString("digen generated code that failed to type-check. This is usually an **internal generator bug**, but it can also happen when a referenced symbol is defined in a `//go:build digen` file (which is excluded at build time, so the generated code cannot see it). In that case move the definition to a non-digen file or an imported package.\n\n")
	b.WriteString("## Generated-file error locations\n")
	b.WriteString("```\n")
	b.WriteString(errorLocations)
	b.WriteString("```\n\n")
	b.WriteString("## Environment\n")
	b.WriteString("- digen (module `github.com/shanjunmei/dig`): please paste `go list -m github.com/shanjunmei/dig` (or the git commit you built from)\n")
	fmt.Fprintf(&b, "- Go: %s\n", runtime.Version())
	fmt.Fprintf(&b, "- OS/Arch: %s/%s\n", runtime.GOOS, runtime.GOARCH)
	b.WriteString("\n## How to reproduce\n")
	b.WriteString("Please attach the source file(s) containing `dig.Build` (the `di.go`) that triggered this generation, plus the exact command you ran (e.g. `digen`).\n")
	b.WriteString("\n_Generated file: `")
	b.WriteString(genFile)
	b.WriteString("`_\n")
	return b.String()
}

// errorInGeneratedFile reports whether a packages.Error's position refers to
// the generated file. It parses the "file:line:col" (or "file:line") Pos string
// robustly, including Windows drive-letter paths (e.g. "c:\\path\\dig_gen.go:12:5").
func errorInGeneratedFile(e packages.Error, genFile string) bool {
	pos := e.Pos
	if pos == "" {
		return false
	}
	file, ok := splitErrorPos(pos)
	if !ok {
		// Without a usable position we cannot attribute the error to the
		// generated file; err on the side of NOT firing the net.
		return false
	}
	cleanGen := filepath.Clean(genFile)
	if filepath.Clean(file) == cleanGen {
		return true
	}
	// Fallback: unique base name within a single package.
	return filepath.Base(file) == filepath.Base(genFile)
}

// collectDigenDefinedMainNames returns the set of top-level names of the main
// package that are declared inside a //go:build digen file. mainPkg is the
// digen-loaded package graph (the loader uses -tags=digen), so its scope sees
// the digen file's symbols. These names are invisible to the generated (!digen)
// file, hence an "undefined: X" for any of them is a contract violation.
func collectDigenDefinedMainNames(mainPkg *packages.Package) map[string]bool {
	res := make(map[string]bool)
	if mainPkg == nil || mainPkg.Types == nil || mainPkg.Fset == nil {
		return res
	}
	files := make(map[string]*ast.File, len(mainPkg.Syntax))
	for _, f := range mainPkg.Syntax {
		files[mainPkg.Fset.Position(f.Package).Filename] = f
	}
	scope := mainPkg.Types.Scope()
	for _, name := range scope.Names() {
		obj := scope.Lookup(name)
		if obj == nil || obj.Pos() == token.NoPos {
			continue
		}
		if obj.Pkg() == nil || obj.Pkg().Path() != mainPkg.PkgPath {
			continue
		}
		fn := mainPkg.Fset.Position(obj.Pos()).Filename
		f, ok := files[fn]
		if !ok {
			continue
		}
		if buildconstraint.FileHasDigenConstraint(f) {
			res[name] = true
		}
	}
	return res
}

// undefinedMainPkgSymbol parses a type-check error message of the form
// "undefined: X" and returns X. It returns ok=false for any other message.
func undefinedMainPkgSymbol(msg string) (string, bool) {
	const prefix = "undefined: "
	if !strings.HasPrefix(msg, prefix) {
		return "", false
	}
	name := strings.TrimSpace(strings.TrimPrefix(msg, prefix))
	// Strip any trailing qualifier such as a method receiver ("undefined: X.Y").
	if i := strings.IndexByte(name, '.'); i >= 0 {
		name = name[:i]
	}
	return name, name != ""
}

// splitErrorPos extracts the file portion of an error position string of the
// form "file:line", "file:line:col", tolerant of ':' inside Windows paths.
func splitErrorPos(pos string) (string, bool) {
	parts := strings.Split(pos, ":")
	// Count trailing numeric segments (line, and optional col).
	n := 0
	for i := len(parts) - 1; i >= 0; i-- {
		if isAllDigits(parts[i]) {
			n++
		} else {
			break
		}
	}
	if n == 0 {
		return "", false
	}
	file := strings.Join(parts[:len(parts)-n], ":")
	if file == "" {
		return "", false
	}
	return file, true
}

// isAllDigits reports whether s is non-empty and consists solely of ASCII digits.
func isAllDigits(s string) bool {
	if s == "" {
		return false
	}
	for i := 0; i < len(s); i++ {
		if s[i] < '0' || s[i] > '9' {
			return false
		}
	}
	return true
}

// getPkgAlias returns the import alias for a package path.
func getPkgAlias(pkgPath string, importAliasMap map[string]string, aliasMap map[string]string, pkgNameMap map[string]string) string {
	if alias, ok := importAliasMap[pkgPath]; ok {
		return alias
	}
	if alias, ok := aliasMap[pkgPath]; ok {
		return alias
	}
	if name, ok := pkgNameMap[pkgPath]; ok {
		return name
	}
	// 理论上不会走到这里，仅作为兜底
	parts := strings.Split(pkgPath, "/")
	return parts[len(parts)-1]
}

// pickCtxParamName selects a context parameter name that does not conflict with
// the context package alias or any other package alias/name used in the generated code.
func pickCtxParamName(ctxAlias string, usedAliases map[string]bool) string {
	candidates := []string{"ctx", "c", "ctxVal", "diCtx", "ctxParam"}
	for _, name := range candidates {
		if name != ctxAlias && !usedAliases[name] {
			return name
		}
	}
	// All common names taken — generate a unique fallback
	for i := 1; ; i++ {
		name := fmt.Sprintf("ctx%d", i)
		if name != ctxAlias && !usedAliases[name] {
			return name
		}
	}
}

// writeImports writes the import block.
func writeImports(buf *bytes.Buffer, mainPkgPath string, importAliasMap map[string]string, pkgAliasMap map[string]string, pkgNameMap map[string]string, usedPkgs []string) {
	importMap := make(map[string]string)
	for _, pkgPath := range usedPkgs {
		if pkgPath == mainPkgPath || pkgPath == "" {
			continue
		}
		importMap[pkgPath] = getPkgAlias(pkgPath, importAliasMap, pkgAliasMap, pkgNameMap)
	}
	paths := functional.Keys(importMap)
	sort.Strings(paths)

	buf.WriteString("import (\n")
	for _, path := range paths {
		alias := importMap[path]
		defaultName := pkgNameMap[path]
		if defaultName == "" {
			defaultName = alias
		}
		// 用户源码显式指定了 alias，必须保留
		if _, ok := importAliasMap[path]; ok {
			fmt.Fprintf(buf, "%s %q\n", alias, path)
			continue
		}

		if alias == defaultName {
			fmt.Fprintf(buf, "%q\n", path)
		} else {
			fmt.Fprintf(buf, "%s %q\n", alias, path)
		}
	}
	buf.WriteString(")\n\n")
}

// writeHeader writes the file header using the template.
func (g *Generator) writeHeader(buf *bytes.Buffer, pkgName string, outFile string) {
	params := g.buildExecParams(outFile)
	fmt.Fprintf(buf, headerTemplate, tagBuild, diPkgPath, tagBuild, params, tagBuild, tagBuild, pkgName)
}

// shouldGenerateProvider determines whether a provider should be generated.
func shouldGenerateProvider(node model.Node, refCount map[string]int, unusedMode model.UnusedMode) bool {
	if unusedMode != model.UnusedModeDrop {
		return true
	}
	return refCount[node.Name] > 0 || node.HasError
}

// writeClosureDefs writes closure provider definitions when needed.
func writeClosureDefs(buf *bytes.Buffer, nodes []model.Node, refCount map[string]int, unusedMode model.UnusedMode) {
	for _, node := range nodes {
		if !node.IsClosure || node.ClosureDef == "" {
			continue
		}
		// Phase 3: Skip closures that will be inlined as IIFE
		if node.ShouldInline {
			continue
		}
		// Phase 4: Skip identity closures (will use direct type conversion)
		if node.IsIdentityClosure {
			continue
		}
		if node.IsInvoke || shouldGenerateProvider(node, refCount, unusedMode) {
			fmt.Fprintf(buf, "%s\n\n", node.ClosureDef)
		}
	}
	if len(nodes) > 0 {
		buf.WriteString("\n")
	}
}

func (g *Generator) buildExecParams(outFile string) string {
	return fmt.Sprintf(" -debug=%v -unused=%s -alias=%s -inline=%v -out=%s", g.cfg.Debug, g.cfg.UnusedMode, g.cfg.AliasType, g.cfg.InlineClosures, outFile)
}

// GenerateCode generates the complete Go source code as a string.
func (g *Generator) GenerateCode(nodes []model.Node, refCount map[string]int, pkgName, originFuncName, mainPkgPath string, importAliasMap, pkgAliasMap, pkgNameMap map[string]string, fset *token.FileSet, params *ast.FieldList, outFile string) (string, error) {
	mainPkg := pkgName
	if mainPkg == "" {
		mainPkg = "main"
	}
	buf := &bytes.Buffer{}

	g.writeHeader(buf, mainPkg, outFile)

	usedPkgSet := make(map[string]bool, len(nodes)+1)
	usedPkgSet["context"] = true
	if g.cfg.Debug {
		usedPkgSet["log"] = true
	}
	for _, node := range nodes {
		if node.PkgPath != "" && node.PkgPath != mainPkgPath {
			usedPkgSet[node.PkgPath] = true
		}
		for _, pkgPath := range node.UsedPkgs {
			usedPkgSet[pkgPath] = true
		}
	}
	usedPkgs := functional.Keys(usedPkgSet)

	writeImports(buf, mainPkgPath, importAliasMap, pkgAliasMap, pkgNameMap, usedPkgs)
	if g.cfg.Debug {
		logPkgPath := "log"
		alias := getPkgAlias(logPkgPath, importAliasMap, pkgAliasMap, pkgNameMap)
		usedPkgSet[logPkgPath] = true
		fmt.Fprintf(buf, "var Logf = %s.Printf\n\n", alias)
	}

	writeClosureDefs(buf, nodes, refCount, g.cfg.UnusedMode)
	g.writeMainFunc(buf, nodes, originFuncName, g.cfg.UnusedMode, refCount, params, fset, importAliasMap, pkgAliasMap, pkgNameMap)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return "", fmt.Errorf("formatting generated code failed: %w\nraw code:\n%s", err, buf.String())
	}
	return string(formatted), nil
}

// formatParams formats the function parameters for the generated function signature.
func formatParams(params *ast.FieldList, fset *token.FileSet) string {
	if params == nil || len(params.List) == 0 {
		return ""
	}
	var buf bytes.Buffer
	for i, field := range params.List {
		if i > 0 {
			buf.WriteString(", ")
		}
		for j, name := range field.Names {
			if j > 0 {
				buf.WriteString(", ")
			}
			buf.WriteString(name.Name)
		}
		buf.WriteString(" ")
		if err := printer.Fprint(&buf, fset, field.Type); err != nil {
			panic(err) // should never happen
		}
	}
	return buf.String()
}

// isLiteral 判断字符串是否为 Go 字面量（数字、字符串、布尔、nil）
func isLiteral(s string) bool {
	if s == "true" || s == "false" || s == "nil" {
		return true
	}
	// 数字：整数、浮点数、复数
	if _, err := strconv.ParseFloat(s, 64); err == nil {
		return true
	}
	// 字符串：以 " 或 ` 开头
	if strings.HasPrefix(s, `"`) || strings.HasPrefix(s, "`") {
		return true
	}
	return false
}

// emitLog writes a debug log statement if debug mode is enabled.
func (g *Generator) emitLog(buf *bytes.Buffer, format string, args ...string) {
	if !g.cfg.Debug {
		return
	}
	if !strings.HasSuffix(format, "\n") {
		format += "\n"
	}
	buf.WriteString("Logf(")
	buf.WriteString(strconv.Quote(format))
	for _, arg := range args {
		buf.WriteString(", ")
		buf.WriteString(arg)
	}
	buf.WriteString(")\n")
}

// buildIIFECall converts a ClosureDef to an IIFE form.
// ClosureDef: "func name(params) returns body"
// Returns:    "func(params) returns body(args)"
func buildIIFECall(node model.Node) string {
	if !node.ShouldInline || node.ClosureDef == "" {
		return ""
	}
	// Strip the function name: "func name(params)..." -> "func(params)..."
	def := node.ClosureDef
	// Find the opening paren ( after the function name
	idx := strings.Index(def, "(")
	if idx < 0 {
		return def
	}
	// Find "func " prefix to skip the name
	funcPrefix := strings.Index(def, "func ")
	if funcPrefix < 0 {
		return def
	}
	// "func name" length is the distance from "func " to the opening paren
	// Replace "func name" with "func"
	paramsStart := idx
	// Skip everything from "func " to "("
	return "func" + def[paramsStart:]
}

// buildIdentityConversion 根据 node 中的信息生成内联表达式字符串
// ctxParamName 是调用上下文中的变量名（即实参表达式）
func buildIdentityConversion(node model.Node, ctxParamName string) string {
	if !node.IsIdentityClosure {
		return ""
	}
	switch node.IdentityOp {
	case model.OpDirect:
		return fmt.Sprintf("%s(%s)", node.IdentityTargetType, ctxParamName)
	case model.OpAddr:
		return fmt.Sprintf("&%s", ctxParamName)
	case model.OpDeref:
		return fmt.Sprintf("*%s", ctxParamName)
	case model.OpConvert:
		return fmt.Sprintf("%s(%s)", node.IdentityTargetType, ctxParamName)
	default:
		return ""
	}
}

// buildCallArgs builds the argument list for a function call from node.Args.
// Const args are skipped since they're inlined as literals in the closure body.
func buildCallArgs(node model.Node, ctxParamName string) []string {
	var args []string
	for _, arg := range node.Args {
		if arg.IsContext {
			args = append(args, ctxParamName)
		} else if arg.IsConst {
			// Phase 1: Const values are inlined in the body, skip in call
			continue
		} else {
			args = append(args, arg.Name)
		}
	}
	return args
}

// writeProvider writes a single provider statement.
// If blank is true, the result is assigned to '_' (unused provider).
// errName is the safe error variable name (avoids shadowing package aliases).
func (g *Generator) writeProvider(buf *bytes.Buffer, node model.Node, blank bool, ctxParamName, errName string) {
	if node.IsSupply {
		expr := node.Value
		// Only qualify the value when it names a package-level symbol of the
		// defining package. Free variables (parameters/locals of the inlined
		// module) are captured by the target scope and must be referenced
		// verbatim — qualifying them yields `undefined: <pkg>.<param>`.
		if node.FuncPkg != "" && node.ValueIsPkgSymbol && !isLiteral(expr) && !strings.HasPrefix(expr, node.FuncPkg+".") {
			expr = node.FuncPkg + "." + expr
		}
		g.emitLog(buf, "[SUPPLY] before: %s", strconv.Quote(node.RetType))
		if node.Comment != "" {
			fmt.Fprintf(buf, "\t%s\n", node.Comment)
		}
		if blank {
			fmt.Fprintf(buf, "_ = %s\n", expr)
		} else {
			fmt.Fprintf(buf, "%s := %s\n", node.Name, expr)
		}
		g.emitLog(buf, "[SUPPLY] after: %s", strconv.Quote(node.RetType))
		return
	}

	logName := node.LongName()

	// Phase 4: Identity closure - use direct type conversion
	if node.IsIdentityClosure {
		identityArgs := buildCallArgs(node, ctxParamName)
		identityParam := ctxParamName
		if len(identityArgs) > 0 {
			identityParam = identityArgs[0]
		}
		conversion := buildIdentityConversion(node, identityParam)
		g.emitLog(buf, "[PROVIDE] identity conversion: %s -> %s", strconv.Quote(logName), strconv.Quote(node.IdentityTargetType))
		if blank {
			fmt.Fprintf(buf, "_ = %s\n", conversion)
		} else {
			fmt.Fprintf(buf, "%s := %s\n", node.Name, conversion)
		}
		g.emitLog(buf, "[PROVIDE] after: %s", strconv.Quote(logName))
		return
	}

	args := buildCallArgs(node, ctxParamName)
	argsStr := strings.Join(args, ", ")

	var fullCall string
	if node.IsClosure {
		if node.ShouldInline {
			fullCall = buildIIFECall(node)
		} else {
			fullCall = node.Func
		}
	} else {
		fullCall = model.FullFuncName(node.FuncPkg, node.Func) + node.GenericArgs
	}

	g.emitLog(buf, "[PROVIDE] before: %s", strconv.Quote(logName))

	if blank {
		if node.HasError {
			// 有error返回，即使结果不用，依然校验错误并panic，保持行为统一
			fmt.Fprintf(buf, "if _, %s := %s(%s); %s != nil {\n", errName, fullCall, argsStr, errName)
			g.emitLog(buf, "[PROVIDE] failed (unused): %s: %v", strconv.Quote(logName), errName)
			fmt.Fprintf(buf, "panic(%s)\n}\n", errName)
		} else {
			fmt.Fprintf(buf, "_ = %s(%s)\n", fullCall, argsStr)
		}
	} else {
		if node.HasError {
			fmt.Fprintf(buf, "%s, %s := %s(%s)\n", node.Name, errName, fullCall, argsStr)
			fmt.Fprintf(buf, "if %s != nil {\n", errName)
			g.emitLog(buf, "[PROVIDE] failed: %s: %v", strconv.Quote(logName), errName)
			fmt.Fprintf(buf, "panic(%s)\n}\n", errName)
		} else {
			fmt.Fprintf(buf, "%s := %s(%s)\n", node.Name, fullCall, argsStr)
		}
	}

	g.emitLog(buf, "[PROVIDE] after: %s", strconv.Quote(logName))
}

// writeProviders writes all provider statements.
func (g *Generator) writeProviders(buf *bytes.Buffer, nodes []model.Node, refCount map[string]int, unusedMode model.UnusedMode, ctxParamName, errName string) {
	for _, node := range nodes {
		if node.IsInvoke {
			continue
		}
		if !shouldGenerateProvider(node, refCount, unusedMode) {
			continue
		}
		blank := false
		if !node.HasError && refCount[node.Name] == 0 && unusedMode == model.UnusedModeIgnore {
			blank = true
		}
		g.writeProvider(buf, node, blank, ctxParamName, errName)
	}
}

// writeInvokes writes all invoke statements.
func (g *Generator) writeInvokes(buf *bytes.Buffer, nodes []model.Node, ctxParamName, errName string) {
	for _, node := range nodes {
		if !node.IsInvoke {
			continue
		}
		logName := node.LongName()

		// Phase 4: Identity closure - use direct type conversion
		if node.IsIdentityClosure {
			identityArgs := buildCallArgs(node, ctxParamName)
			identityParam := ctxParamName
			if len(identityArgs) > 0 {
				identityParam = identityArgs[0]
			}
			conversion := buildIdentityConversion(node, identityParam)
			g.emitLog(buf, "[INVOKE] identity conversion: %s -> %s", strconv.Quote(logName), strconv.Quote(node.IdentityTargetType))
			if node.HasError {
				fmt.Fprintf(buf, "if %s := %s; %s != nil {\n", errName, conversion, errName)
				g.emitLog(buf, "[INVOKE] failed: %s: %v", strconv.Quote(logName), errName)
				fmt.Fprintf(buf, "return %s\n}\n", errName)
			} else {
				fmt.Fprintf(buf, "%s\n", conversion)
			}
			g.emitLog(buf, "[INVOKE] after: %s", strconv.Quote(logName))
			continue
		}

		args := buildCallArgs(node, ctxParamName)
		argsStr := strings.Join(args, ", ")

		var fullCall string
		if node.IsClosure {
			if node.ShouldInline {
				fullCall = buildIIFECall(node)
			} else {
				fullCall = node.Func
			}
		} else {
			fullCall = model.FullFuncName(node.FuncPkg, node.Func) + node.GenericArgs
		}

		g.emitLog(buf, "[INVOKE] before: %s", strconv.Quote(logName))

		if node.HasError {
			fmt.Fprintf(buf, "if %s := %s(%s); %s != nil {\n", errName, fullCall, argsStr, errName)
			g.emitLog(buf, "[INVOKE] failed: %s: %v", strconv.Quote(logName), errName)
			fmt.Fprintf(buf, "return %s\n}\n", errName)
		} else {
			fmt.Fprintf(buf, "%s(%s)\n", fullCall, argsStr)
		}

		g.emitLog(buf, "[INVOKE] after: %s", strconv.Quote(logName))
	}
}

// writeMainFunc writes the main generated function.
func (g *Generator) writeMainFunc(buf *bytes.Buffer, nodes []model.Node, originFuncName string, unusedMode model.UnusedMode, refCount map[string]int, params *ast.FieldList, fset *token.FileSet, importAliasMap, pkgAliasMap, pkgNameMap map[string]string) {
	paramStr := formatParams(params, fset)
	if paramStr != "" {
		paramStr = " " + paramStr
	}
	// ShadowGuard 统一收集所有包标识符 + Go 内建标识符，
	// 供 ctxParam 和 err 变量名查询，避免生成变量遮蔽包别名。
	sg := alias.NewShadowGuard(importAliasMap, pkgAliasMap, pkgNameMap)
	ctxAlias := getPkgAlias("context", importAliasMap, pkgAliasMap, pkgNameMap)
	ctxParam := pickCtxParamName(ctxAlias, sg.Reserved())
	errName := sg.SafeName("err")
	fmt.Fprintf(buf, "func %s(%s) func(%s.Context) error {\n", originFuncName, paramStr, ctxAlias)
	g.writeProviders(buf, nodes, refCount, unusedMode, ctxParam, errName)
	fmt.Fprintf(buf, "\treturn func(%s %s.Context) error {\n", ctxParam, ctxAlias)
	g.writeInvokes(buf, nodes, ctxParam, errName)
	buf.WriteString("\t\treturn nil\n\t}\n}\n\n")
}
